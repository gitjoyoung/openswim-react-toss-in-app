-- 관공서 공휴일. 앱이 '오늘 공휴일인가'를 판정해 공휴일 시간표(day=7)를 보여줄지 정하는 데 쓴다.
--
-- 왜 DB로 빼는가:
--   1. 음력 명절과 대체공휴일은 매년 날짜가 달라 해마다 갱신해야 한다.
--   2. 임시공휴일은 정부가 국무회의로 수시 지정한다(관공서공휴일규정 제2조 제11호, 제4조).
--      보통 1~2주 전에 정해지는데, 앱 검수 기간을 생각하면 배포로는 못 맞춘다.
--   3. 값이 틀리면 평일 시간표를 공휴일에 그대로 보여주게 된다. 사용자가 헛걸음한다.
--
-- 권한은 public.pools 와 같다: RLS 켜고 anonymous 읽기 전용.
create table if not exists public.holidays (
  -- KST 기준 날짜. 앱도 기기 로컬(KST) 날짜로 조회한다.
  date date primary key,
  -- 화면에 쓰지는 않고 운영자가 무슨 날인지 알아보는 용도다.
  name text not null,
  -- 근거를 남긴다. 월력요항인지, 임시공휴일 국무회의 의결인지.
  source text,
  updated_at timestamptz not null default now()
);

