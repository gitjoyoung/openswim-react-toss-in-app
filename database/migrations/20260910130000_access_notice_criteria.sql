-- 이용 제한 배지 기준을 좁힌다.
--
-- 이 앱은 비회원이 오늘 가서 자유수영을 할 수 있는지를 본다.
-- 그래서 배지에는 **신분 때문에 입장이 막히는 경우**만 넣는다.
--   예) 여성 전용, 특정 연령 입장 불가, 장애인 전용
--
-- 넣지 않는 것:
--   · 회원 전용 시간대 → 우리 데이터는 애초에 비회원 일일권 기준이다. 굳이 알릴 값이 아니다.
--   · 특정 요일에만 자유수영 → 시간표가 이미 그대로 보여준다. 배지로 또 쓰면 중복이다.
--   · 방역·수질정화 등 시간대 운영 → 사람 기준 제한이 아니다.
--
-- 앞선 마이그레이션에서 넣은 4건 중 3건이 위 기준에 걸려 지운다.
-- 원문은 price_note / free_swim_note 에 그대로 남아 있어 정보가 사라지지는 않는다.

-- 회원 전용 시간대. 비회원 기준인 우리 데이터에서는 알릴 값이 아니다.
update public.pools
   set access_label = null, access_note = null
 where name = '용산문화체육센터';

-- 평일 자유수영이 없다는 뜻인데, free_swim 에 평일 세션이 0개로 이미 들어 있다.
-- 시간표가 말하는 것을 배지로 반복하지 않는다.
update public.pools
   set access_label = null, access_note = null
 where name = '감일복합커뮤니티센터 수영장';

-- '유소년 중심'은 성인이 이용할 수 있는지를 알려주지 못한다.
-- 요금표에 성인·청소년·어린이가 모두 있어 성인 이용 자체는 가능해 보인다.
-- 시간대를 확인하라는 안내는 요금 비고(price_note)에 그대로 있으므로 배지에서는 뺀다.
update public.pools
   set access_label = null, access_note = null
 where name = '강동유소년스포츠센터 수영장';

-- 남는 것은 연령 기준으로 입장이 막히는 이 한 건이다.
--   언북문화체육센터 → '어린이 입장 제한' / '토요일 06:00~10:50은 어린이가 입장할 수 없습니다.'
