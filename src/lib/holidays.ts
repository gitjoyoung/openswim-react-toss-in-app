export const BUNDLED_HOLIDAY_COUNT = Object.keys(BUNDLED_HOLIDAYS).length;

// isHoliday() 는 목록 렌더링 중 행마다 불리는 동기 함수라 비동기로 바꾸지 않는다.
// DB 값이 도착하면 이 표를 갈아끼우고, 화면은 useHolidays 훅이 다시 그린다.
let holidays: Record<string, string> = BUNDLED_HOLIDAYS;

// DB에서 받은 표로 교체한다. 빈 응답이면 번들 표를 유지한다.
// 잘못된 update 하나로 전국 공휴일이 통째로 사라지는 것보다는 예전 표가 낫다.
export function setHolidays(next: Record<string, string>): boolean {
  if (!next || Object.keys(next).length === 0) return false;
  holidays = next;
  return true;
}

export function resetHolidays(): void {
  holidays = BUNDLED_HOLIDAYS;
}

// 로컬(기기 시간=KST) 기준 yyyy-mm-dd 키. UTC로 밀리지 않게 로컬 필드로 조립.
function dateKey(d: Date): string {
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

// 오늘(또는 주어진 날짜)이 공휴일인가.
export function isHoliday(d = new Date()): boolean {
  return dateKey(d) in holidays;
}

// 공휴일이면 이름("설날" 등), 아니면 null.
export function holidayName(d = new Date()): string | null {
  return holidays[dateKey(d)] ?? null;
}
